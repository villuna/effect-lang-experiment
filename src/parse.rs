//! Functions for parsing a program from an input string to an abstract syntax tree.

// Most of the functions in this module are of the form parse_RULE which simply transforms the
// concrete syntax tree given to us by Pest's parser and turns it into the abstract syntax tree.

use std::sync::LazyLock;

use pest::{
    Parser,
    iterators::Pairs,
    pratt_parser::{Assoc, Op, PrattParser},
};
use pest_derive::Parser;

use crate::ast::{
    BinOp, Block, Expression, ExpressionKind, FunctionDef, FunctionParam, Item, ItemKind,
    ProgramTree, Statement, StatementKind, Type, UnaryOp, Value, VariableAssign, VariableDef,
};

type ParseResult<T> = Result<T, pest::error::Error<Rule>>;

/// This struct holds code auto-generated by pest to parse text to a (non-abstract) syntax tree.
#[derive(Parser)]
#[grammar = "grammar.pest"]
struct LangParser;

/// A Pratt parser allows us to parse binary operations with precedence defined here, outside of
/// the grammar.
///
/// The precedence order is defined by a sequence of calls to .op(...), with lowest precedence
/// first.
static PRATT_PARSER: LazyLock<PrattParser<Rule>> = LazyLock::new(|| {
    PrattParser::new()
        .op(Op::infix(Rule::eq, Assoc::Left) | Op::infix(Rule::neq, Assoc::Left))
        .op(Op::infix(Rule::and, Assoc::Left) | Op::infix(Rule::or, Assoc::Left))
        .op(Op::infix(Rule::gt, Assoc::Left)
            | Op::infix(Rule::geq, Assoc::Left)
            | Op::infix(Rule::lt, Assoc::Left)
            | Op::infix(Rule::leq, Assoc::Left))
        .op(Op::infix(Rule::add, Assoc::Left) | Op::infix(Rule::sub, Assoc::Left))
        .op(Op::infix(Rule::mult, Assoc::Left) | Op::infix(Rule::div, Assoc::Left))
        .op(Op::prefix(Rule::not) | Op::prefix(Rule::neg))
});

/// Parses the entire text of a program file and converts it into an abstract syntax tree
/// representing the declarations in the file.
pub fn parse(source: &str) -> ParseResult<ProgramTree> {
    let parse = LangParser::parse(Rule::program, source)?.next().unwrap();

    let items = parse
        .into_inner()
        .filter_map(|parsed| match parsed.as_rule() {
            Rule::item => Some(parse_item(parsed.into_inner())),
            Rule::EOI => None,
            _ => unreachable!(),
        })
        .collect::<ParseResult<_>>()?;

    Ok(ProgramTree { items })
}

fn parse_item(mut input: Pairs<'_, Rule>) -> ParseResult<Item> {
    let rule = input.next().unwrap();

    let kind = match rule.as_rule() {
        Rule::function_def => ItemKind::Function(parse_function_def(rule.into_inner())?),
        Rule::variable_def => ItemKind::Static(parse_variable_def(rule.into_inner())?),
        _ => unreachable!(),
    };

    Ok(Item { kind })
}

// variable_def = { "let" ~ ident ~ (":" ~ type)? ~ "=" ~ expression }
fn parse_variable_def(mut input: Pairs<'_, Rule>) -> ParseResult<VariableDef> {
    let name = input.next().unwrap();
    let mut ty = None;
    let mut value = None;

    for pair in input {
        match pair.as_rule() {
            Rule::r#type => ty = Some(parse_type(pair.into_inner())?),
            Rule::expression => value = Some(parse_expression(pair.into_inner())?),
            _ => unreachable!(),
        }
    }

    Ok(VariableDef {
        name: name.to_string(),
        ty,
        value: value.unwrap(),
    })
}

// function_def = { "fun" ~ ident ~ "(" ~ params_list? ~ ")" ~ ("->" ~ type)? ~ block }
fn parse_function_def(mut input: Pairs<'_, Rule>) -> ParseResult<FunctionDef> {
    let name = input.next().unwrap();

    let name = match name.as_rule() {
        Rule::ident => name.to_string(),
        _ => unreachable!(),
    };

    let mut params = Vec::new();
    let mut return_type = None;
    let mut block = None;

    for pair in input {
        match pair.as_rule() {
            Rule::params_list => params = parse_params_list(pair.into_inner())?,
            Rule::r#type => return_type = Some(parse_type(pair.into_inner())?),
            Rule::block => block = Some(parse_block(pair.into_inner())?),
            _ => unreachable!(),
        }
    }

    Ok(FunctionDef {
        name,
        params,
        block: block.unwrap(),
        return_type,
    })
}

fn parse_params_list(input: Pairs<'_, Rule>) -> ParseResult<Vec<FunctionParam>> {
    input
        .map(|param| {
            assert_eq!(param.as_rule(), Rule::param);
            parse_param(param.into_inner())
        })
        .collect()
}

// param = { ident ~ ":" ~ type }
fn parse_param(mut input: Pairs<'_, Rule>) -> ParseResult<FunctionParam> {
    let name = input.next().unwrap();
    assert_eq!(name.as_rule(), Rule::ident);
    let ty = input.next().unwrap();

    Ok(FunctionParam {
        name: name.to_string(),
        ty: parse_type(ty.into_inner())?,
    })
}

fn parse_block(mut input: Pairs<'_, Rule>) -> ParseResult<Block> {
    let statements = input.next().unwrap().into_inner();
    let mut result = Block {
        statements: vec![],
        value: None,
    };

    for pair in statements {
        match pair.as_rule() {
            Rule::statement => {
                result.statements.push(parse_statement(pair.into_inner())?);
            }
            Rule::expression => {
                result.value = Some(Box::new(parse_expression(pair.into_inner())?));
            }
            _ => panic!(
                "encountered unexpected rule \"{:?}\"\ninput: \"{}\"",
                pair.as_rule(),
                pair.as_str()
            ),
        }
    }

    Ok(result)
}

fn parse_statement(mut input: Pairs<'_, Rule>) -> ParseResult<Statement> {
    let rule = input.next().unwrap();

    let kind = match rule.as_rule() {
        Rule::variable_def => StatementKind::Variable(parse_variable_def(rule.into_inner())?),
        Rule::expression => StatementKind::Expression(parse_expression(rule.into_inner())?),
        Rule::assignment => StatementKind::Assignment(parse_assignment(rule.into_inner())?),
        _ => unreachable!(),
    };

    Ok(Statement { kind })
}

// assignment = { ident ~ "=" ~ expression }
fn parse_assignment(mut input: Pairs<'_, Rule>) -> ParseResult<VariableAssign> {
    let var = input.next().unwrap().to_string();
    let expr = parse_expression(input.next().unwrap().into_inner())?;

    Ok(VariableAssign { var, expr })
}

fn parse_expression(input: Pairs<'_, Rule>) -> ParseResult<Expression> {
    PRATT_PARSER
        .map_primary(|pair| parse_primary(pair.into_inner()))
        .map_infix(|lhs, op, rhs| {
            let lhs = lhs?;
            let rhs = rhs?;
            let Some(op) = BinOp::from_rule(op.as_rule()) else {
                unreachable!()
            };

            Ok(Expression {
                kind: ExpressionKind::BinOp(Box::new(lhs), op, Box::new(rhs)),
            })
        })
        .map_prefix(|op, expr| {
            let expr = expr?;
            let Some(op) = UnaryOp::from_rule(op.as_rule()) else {
                unreachable!()
            };
            Ok(Expression {
                kind: ExpressionKind::UnaryOp(op, Box::new(expr)),
            })
        })
        .parse(input)
}

fn parse_primary(mut input: Pairs<'_, Rule>) -> ParseResult<Expression> {
    let input = input.next().unwrap();

    if matches!(input.as_rule(), Rule::expression) {
        return parse_expression(input.into_inner());
    }

    let kind = match input.as_rule() {
        Rule::unit => ExpressionKind::Value(Value::Unit),
        Rule::number => {
            let mut inner_input = input.clone().into_inner();
            let int_part = inner_input.next().unwrap();
            let decimal_part = inner_input.next();
            let exponential_part = inner_input.next();

            if matches!((decimal_part, exponential_part), (None, None)) {
                assert!(matches!(int_part.as_rule(), Rule::int));
                ExpressionKind::Value(Value::Int(int_part.as_str().parse().unwrap()))
            } else {
                ExpressionKind::Value(Value::Float(input.as_str().parse().unwrap()))
            }
        }
        Rule::string => {
            let input = input.into_inner().next().unwrap();

            // TODO handle escape chars
            ExpressionKind::Value(Value::String(input.to_string()))
        }
        Rule::function_call => {
            let mut input = input.into_inner();
            let name = input.next().unwrap();
            let mut parameters = Vec::new();

            for expr in input {
                match expr.as_rule() {
                    Rule::expression => parameters.push(parse_expression(expr.into_inner())?),
                    _ => unreachable!(),
                }
            }

            ExpressionKind::FunctionCall {
                function: name.to_string(),
                parameters,
            }
        }
        Rule::ident => ExpressionKind::Var(input.to_string()),
        Rule::block => ExpressionKind::Block(parse_block(input.into_inner())?),
        Rule::bool => ExpressionKind::Value(Value::Bool(input.as_str() == "true")),
        Rule::conditional => {
            let mut input = input.into_inner();
            let condition = input.next().unwrap();
            assert_eq!(condition.as_rule(), Rule::expression);
            let condition = parse_expression(condition.into_inner())?;

            let if_path = input.next().unwrap();
            assert_eq!(if_path.as_rule(), Rule::block);
            let if_path = Expression {
                kind: ExpressionKind::Block(parse_block(if_path.into_inner())?),
            };

            // We need to clone this as if the next part of the if statement is another conditional,
            // we have to parse the entire conditional.
            let else_path: Option<Expression> = input
                .clone()
                .next()
                .map(|else_path| match else_path.as_rule() {
                    Rule::block => Ok(Expression {
                        kind: ExpressionKind::Block(parse_block(else_path.into_inner())?),
                    }),
                    Rule::conditional => parse_primary(input),
                    _ => unreachable!(),
                })
                .transpose()?;

            ExpressionKind::Conditional {
                condition: Box::new(condition),
                if_path: Box::new(if_path),
                else_path: else_path.map(Box::new),
            }
        }
        _ => unreachable!(),
    };

    Ok(Expression { kind })
}

fn parse_type(mut input: Pairs<'_, Rule>) -> ParseResult<Type> {
    Ok(match input.next().unwrap().as_str() {
        "string" => Type::String,
        "int" => Type::Int,
        "float" => Type::Float,
        "bool" => Type::Bool,
        _ => unreachable!(),
    })
}
